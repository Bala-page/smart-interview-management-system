/**
 * Seeds sample questions into MongoDB if the collection is empty
 */
const seedQuestionBank = async (recruiterUserId = null) => {
  let inserted = 0;

  for (const q of sampleQuestions) {
    const exists = await AssessmentQuestion.findOne({ questionText: q.questionText });
    if (!exists) {
      await AssessmentQuestion.create({
        ...q,
        createdBy: recruiterUserId || null,
        isActive: true,
      });
      inserted++;
    }
  }

  const totalInDb = await AssessmentQuestion.countDocuments();
  console.log(`[QuestionBank] Seed check complete: ${inserted} new questions added. Total in database: ${totalInDb}.`);
  return totalInDb;
};

